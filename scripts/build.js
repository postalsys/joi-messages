// Builds the package.
//
// Compiles src/ twice with tsc: once as ES modules into dist/esm and once as CommonJS into
// dist/cjs. Each output directory gets its own package.json that pins the module format.
//
// The translations are parsed here, not at runtime: translations/translations.json maps a locale
// code (de_DE) to a .po file, each .po file is read with gettext-parser (a devDependency), and the
// resulting { <language>: { <joi code>: <template> } } map is written into both builds as
// messages-data.js, which src/index.ts imports (src/messages-data.d.ts declares it). The published
// package then has no runtime dependencies and reads no files. translations/ is still published
// unchanged at the package root.
//
// Every other module keeps the exports tsc gives it: src/index.ts has a named export plus a
// default export object, so `require('@postalsys/joi-messages')` keeps returning an object with
// messages().

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tsc = require.resolve('typescript/bin/tsc');
const gettextParser = require('gettext-parser');

function runTsc(project, ...args) {
    const result = spawnSync(process.execPath, [tsc, '-p', project, ...args], { cwd: root, stdio: 'inherit' });
    if (result.status !== 0) {
        process.exit(result.status || 1);
    }
}

fs.rmSync(path.join(root, 'dist'), { recursive: true, force: true });

runTsc('tsconfig.esm.json');
// The ES module compile has already type-checked the same sources
runTsc('tsconfig.cjs.json', '--noCheck');

// Each entry's reference comment (`#: any.unknown object.unknown`) lists the Joi codes it applies
// to, one entry can carry several codes that share the same English message. An empty msgstr
// falls back to the English msgid.
function generateMessages() {
    const translationsDir = path.join(root, 'translations');
    const translationList = JSON.parse(fs.readFileSync(path.join(translationsDir, 'translations.json'), 'utf-8'));
    const result = {};
    for (const [code, file] of Object.entries(translationList)) {
        const translations = gettextParser.po.parse(fs.readFileSync(path.join(translationsDir, file)));
        const languageMessages = {};
        for (const [msgid, entry] of Object.entries(translations.translations[''] || {})) {
            const reference = entry.comments?.reference;
            if (!code || !reference) {
                continue;
            }
            for (const joiCode of reference.trim().split(/\s+/)) {
                languageMessages[joiCode] = entry.msgstr[0] || msgid;
            }
        }
        result[code.split('_')[0]] = languageMessages;
    }
    return result;
}

const messagesJson = JSON.stringify(JSON.stringify(generateMessages()));
const header = '// Generated by scripts/build.js from translations/*.po, see src/messages-data.d.ts';
fs.writeFileSync(path.join(root, 'dist', 'esm', 'messages-data.js'), [header, `export const MESSAGES_JSON = ${messagesJson};`, ''].join('\n'));
fs.writeFileSync(
    path.join(root, 'dist', 'cjs', 'messages-data.js'),
    ['"use strict";', header, 'Object.defineProperty(exports, "__esModule", { value: true });', `exports.MESSAGES_JSON = ${messagesJson};`, ''].join('\n')
);

fs.writeFileSync(path.join(root, 'dist', 'esm', 'package.json'), JSON.stringify({ type: 'module' }, null, 4) + '\n');
fs.writeFileSync(path.join(root, 'dist', 'cjs', 'package.json'), JSON.stringify({ type: 'commonjs' }, null, 4) + '\n');
