// Builds the package.
//
// Compiles src/ twice with tsc: once as ES modules into dist/esm and once as CommonJS into
// dist/cjs. Each output directory gets its own package.json that pins the module format.
//
// src/package-root.ts finds the package root through import.meta.url, which does not exist in
// CommonJS, so its CommonJS output is replaced with the __dirname equivalent. Both builds sit two
// levels below the root and read translations/ from there, the directory EmailEngine bundles as
// pkg assets.
//
// Every other module keeps the exports tsc gives it: src/index.ts has a named export plus a
// default export object, so `require('@postalsys/joi-messages')` keeps returning an object with
// messages().

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tsc = require.resolve('typescript/bin/tsc');

function runTsc(project, ...args) {
    const result = spawnSync(process.execPath, [tsc, '-p', project, ...args], { cwd: root, stdio: 'inherit' });
    if (result.status !== 0) {
        process.exit(result.status || 1);
    }
}

fs.rmSync(path.join(root, 'dist'), { recursive: true, force: true });

runTsc('tsconfig.esm.json');
// The ES module compile has already type-checked the same sources
runTsc('tsconfig.cjs.json', '--noCheck');

fs.writeFileSync(
    path.join(root, 'dist', 'cjs', 'package-root.js'),
    [
        '"use strict";',
        '// Generated by scripts/build.js, the CommonJS form of src/package-root.ts',
        'Object.defineProperty(exports, "__esModule", { value: true });',
        'exports.packageRoot = void 0;',
        'const node_path_1 = require("node:path");',
        'exports.packageRoot = node_path_1.resolve(__dirname, "..", "..");',
        ''
    ].join('\n')
);

fs.writeFileSync(path.join(root, 'dist', 'esm', 'package.json'), JSON.stringify({ type: 'module' }, null, 4) + '\n');
fs.writeFileSync(path.join(root, 'dist', 'cjs', 'package.json'), JSON.stringify({ type: 'commonjs' }, null, 4) + '\n');
